#!/usr/bin/env python3
"""
Converts the 2D Pixel City Pack sprite sheets (laavis, CC-BY 4.0,
https://opengameart.org/content/2d-pixel-city-pack) into C arrays.

Usage: python3 tools/gen_assets.py <10102017.png> <Spritesheet.png> <out_dir> [CITY_MEGA.png]

Optional CITY_MEGA.png ("City Mega Pack" by GrafxKid, CC0,
https://opengameart.org/content/city-mega-pack) adds the residents who look
out of the windows and the daytime sky with the far city.
Writes assets.c and assets.h. Each sprite gets its own palette (index 0 =
transparent). Floor modules also get a "glass" mask so windows can be lit.
"""
import sys
import numpy as np
from PIL import Image
from scipy import ndimage

sheet_a = Image.open(sys.argv[1]).convert("RGBA")   # 10102017.png
sheet_b = Image.open(sys.argv[2]).convert("RGBA")   # Spritesheet.png
out_dir = sys.argv[3]
mega = Image.open(sys.argv[4]).convert("RGBA") if len(sys.argv) > 4 else None

# name: (sheet, x, y, w, h)
CROPS = {
    "brown":      (sheet_a, 3, 6, 132, 187),
    "graffiti_a": (sheet_a, 150, 25, 52, 27),
    "graffiti_b": (sheet_a, 238, 70, 78, 22),
    "railing":    (sheet_a, 223, 25, 29, 24),
    "brick":      (sheet_a, 273, 6, 32, 56),
    "bus_sign":   (sheet_a, 331, 13, 27, 86),
    "tire":       (sheet_a, 147, 70, 29, 29),
    "bus":        (sheet_a, 147, 105, 224, 88),
    "tree_green": (sheet_a, 371, 72, 51, 120),
    "tree_orange":(sheet_a, 437, 72, 51, 120),
    "tree_purple":(sheet_a, 505, 72, 51, 121),
    "skyline_a":  (sheet_a, 577, 34, 384, 191),
    "skyline_b":  (sheet_a, 422, 252, 384, 186),
    "club":       (sheet_b, 10, 8, 128, 162),
    "shop":       (sheet_b, 286, 25, 140, 128),
    "wall_tile":  (sheet_b, 10, 193, 32, 32),
    "rope":       (sheet_b, 226, 204, 32, 21),
    "fruit_a":    (sheet_b, 16, 251, 23, 30),
    "fruit_b":    (sheet_b, 70, 251, 23, 30),
    "skyline_far":(sheet_b, 19, 302, 384, 191),
}
SKY = (sheet_a, 12, 214, 384, 224)   # vertical gradient: one column is enough

# Floor modules: cap = rows [0, cap_end), mid = [mid_start, base_start), base = [base_start, h)
KITS = {"club": (10, 10, 50), "shop": (13, 13, 48), "brown": (12, 26, 75)}

def crop(name):
    s, x, y, w, h = CROPS[name]
    return np.array(s.crop((x, y, x + w, y + h))).astype(np.uint8)

def glass_mask(mid):
    h, w = mid.shape[:2]
    key = (mid[:, :, 0].astype(np.int64) << 16) | (mid[:, :, 1].astype(np.int64) << 8) | mid[:, :, 2]
    wall = set(np.unique(key[0:2, :])) | set(np.unique(key[:, :16])) | set(np.unique(key[:, w - 16:]))
    nonwall = np.isin(key, list(wall), invert=True) & (mid[:, :, 3] > 0)
    lab, _ = ndimage.label(nonwall)
    glass = np.zeros((h, w), bool)
    for i, sl in enumerate(ndimage.find_objects(lab)):
        comp = lab[sl] == i + 1
        if comp.sum() < 60:
            continue
        er = ndimage.binary_erosion(comp, iterations=2)
        ring_cols = set(key[sl][comp & ~er])
        glass[sl] |= er & np.isin(key[sl], list(ring_cols), invert=True)
    return glass

def to_indexed(rgba):
    h, w = rgba.shape[:2]
    pal = [0]                       # index 0 = transparent
    lut = {}
    idx = np.zeros((h, w), np.uint8)
    for y in range(h):
        for x in range(w):
            r, g, b, a = (int(v) for v in rgba[y, x])
            if a < 128:
                continue
            abgr = 0xFF000000 | (b << 16) | (g << 8) | r
            if abgr not in lut:
                lut[abgr] = len(pal)
                pal.append(abgr)
                if len(pal) > 256:
                    raise SystemExit("too many colors")
            idx[y, x] = lut[abgr]
    return idx, pal

sprites = []   # (cname, array, glass or None)
for name in CROPS:
    if name in KITS:
        continue
    sprites.append((name, crop(name), None))
for name, (ce, ms, bs) in KITS.items():
    full = crop(name)
    sprites.append((name + "_cap", full[:ce], None))
    sprites.append((name + "_mid", full[ms:bs], glass_mask(full[ms:bs])))
    sprites.append((name + "_base", full[bs:], None))
if mega is not None:
    # residents: front-facing characters; the sheet's two background colors become transparent
    RESIDENTS = [(104, 76, 16, 20), (104, 108, 16, 20), (102, 162, 21, 30), (102, 228, 21, 28),
                 (360, 172, 16, 20), (360, 238, 17, 18), (294, 104, 19, 24), (105, 304, 15, 16),
                 (362, 305, 12, 15), (360, 396, 16, 20), (105, 401, 13, 15), (585, 428, 14, 20)]
    for i, (x, y, w, h) in enumerate(RESIDENTS):
        a = np.array(mega.crop((x, y, x + w, y + h))).copy()
        for kc in ((130, 117, 79), (90, 81, 55)):
            m = (np.abs(a[:, :, :3].astype(int) - np.array(kc)).sum(axis=2) < 6)
            a[m, 3] = 0
        sprites.append(("resident_%d" % i, a, None))
    sprites.append(("day_sky", np.array(mega.crop((64, 2400, 544, 2720))), None))

tire = crop("tire")
for k in range(1, 4):   # rotated frames for rolling wheels
    sprites.append(("tire_%d" % k, np.rot90(tire, -k).copy(), None))

c = ["/* Generated by tools/gen_assets.py - do not edit.",
     " * Art: \"2D Pixel City Pack\" by laavis, CC-BY 4.0",
     " * Residents and day sky: \"City Mega Pack\" by GrafxKid, CC0",
     " * https://opengameart.org/content/2d-pixel-city-pack */",
     '#include "assets.h"', ""]
h = ["/* Generated by tools/gen_assets.py - do not edit. */",
     "#ifndef POMO_ASSETS_H", "#define POMO_ASSETS_H", '#include "gfx.h"', ""]
total = 0
for name, arr, glass in sprites:
    idx, pal = to_indexed(arr)
    hh, ww = idx.shape
    total += ww * hh + len(pal) * 4
    c.append("static const uint32_t %s_pal[%d] = {%s};" % (name, len(pal), ",".join("0x%08X" % p for p in pal)))
    c.append("static const uint8_t %s_px[%d] = {%s};" % (name, ww * hh, ",".join(str(int(v)) for v in idx.flatten())))
    gname = "0"
    if glass is not None:
        c.append("static const uint8_t %s_glass[%d] = {%s};" % (name, ww * hh, ",".join("1" if v else "0" for v in glass.flatten())))
        gname = "%s_glass" % name
        total += ww * hh
    c.append("const Sprite SPR_%s = { %d, %d, %s_px, %s_pal, %s };" % (name.upper(), ww, hh, name, name, gname))
    c.append("")
    h.append("extern const Sprite SPR_%s;" % name.upper())

s, x, y, w, hgt = SKY
col = np.array(s.crop((x, y, x + w, y + hgt)))[:, w // 2]
c.append("const uint32_t SKY_GRADIENT[%d] = {%s};" % (hgt, ",".join(
    "0x%08X" % (0xFF000000 | (int(p[2]) << 16) | (int(p[1]) << 8) | int(p[0])) for p in col)))
h.append("#define SKY_GRADIENT_H %d" % hgt)
h.append("extern const uint32_t SKY_GRADIENT[%d];" % hgt)
if mega is not None:
    h.append("#define RESIDENT_COUNT 12")
    h.append("extern const Sprite *const RESIDENTS[RESIDENT_COUNT];")
    c.append("const Sprite *const RESIDENTS[12] = {%s};" % ",".join("&SPR_RESIDENT_%d" % i for i in range(12)))
h += ["", "#endif", ""]

open(out_dir + "/assets.c", "w").write("\n".join(c) + "\n")
open(out_dir + "/assets.h", "w").write("\n".join(h))
print("sprites:", len(sprites), " approx bytes:", total)
